"""Build video 016's narration and plan documents from plan/scenes.yaml (the source of truth).

Writes (generated files: edit plan/scenes.yaml, then re-run this):
    voiceover.md              aion's narration script: chapter headings, `<!-- scene: id -->` markers, inline
                              `[pause N]` marks, and a `> [pause N]` note for each scene's silent beat
    script/narration_full.md  the full script to read aloud, with words and estimated times per scene
    plan/scene_plan.md        the readable scene plan (per chapter: concept table; per scene: every field)
    storyboard.md             a pointer to plan/scene_plan.md (aion's storyboard file)
It also fills `duration_s` in plan/scenes.yaml for every scene whose `duration_source` is `estimate`, and checks
that each `reveal_sequence[].at_word` appears in its scene's narration, in order.

Estimates: speech time = words / wpm, plus the inline pauses, plus the scene's silent beat (`pause_after_s`).
The default 166 wpm is the channel voice's natural rate at speed 0.90 (measured 168-171 wpm at 0.92 on videos
013 and 014). After the speed test, pass the measured rate with --wpm. After voicing, scripts/timing.py replaces
the estimates with real durations (duration_source: audio), and this script leaves those alone.

Usage (from the repo root):
    uv run python videos/016-pca-explained/scripts/build_script.py [--wpm 166] [--check]
--check only validates and prints the summary; it writes nothing.
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

from ruamel.yaml import YAML

VIDEO = Path(__file__).resolve().parents[1]
SCENES = VIDEO / "plan" / "scenes.yaml"
PAUSE = re.compile(r"\[pause\s+(\d+(?:\.\d*)?|\.\d+)\s*s?\s*\]", re.I)
TRAILING_PAUSE = re.compile(r"\s*\[pause\s+(\d+(?:\.\d*)?|\.\d+)\s*s?\s*\]\s*$", re.I)
WORD = re.compile(r"[A-Za-z0-9]+(?:['’-][A-Za-z0-9]+)*")
GENERATED = "Generated by scripts/build_script.py from plan/scenes.yaml. Edit that file, then re-run the script."


def load() -> dict:
    return YAML(typ="safe").load(SCENES.read_text())


def flat(text: str) -> str:
    """Narration as one line, marks kept."""
    return " ".join(str(text).split())


def spoken(text: str) -> str:
    """What the voice says: pause marks and emphasis stars removed."""
    return " ".join(PAUSE.sub(" ", str(text)).replace("*", "").split())


def words(text: str) -> list[str]:
    return [w.lower().replace("’", "'") for w in WORD.findall(spoken(text))]


def split_trailing(text: str) -> tuple[str, float]:
    """(narration without a final [pause N], that N). A pause after the last word belongs to the silent beat."""
    m = TRAILING_PAUSE.search(text)
    return (text[: m.start()], float(m.group(1))) if m else (text, 0.0)


def inline_pauses(text: str) -> float:
    return sum(float(x) for x in PAUSE.findall(text))


def mmss(t: float) -> str:
    t = int(round(t))
    return f"{t // 60}:{t % 60:02d}"


def check_cues(scene: dict) -> list[str]:
    """Each at_word must be found in the narration after the previous one (as aion's beats() searches)."""
    ws, errors, pos = words(scene["narration"]), [], -1
    for step in scene.get("visual", {}).get("reveal_sequence", []) or []:
        phrase = words(step["at_word"])
        hit = next((i for i in range(pos + 1, len(ws) - len(phrase) + 1) if ws[i:i + len(phrase)] == phrase), None)
        if hit is None:
            errors.append(f"{scene['id']}: at_word {step['at_word']!r} not found after word {pos + 1}")
        else:
            pos = hit
    return errors


def plan(data: dict, wpm: float) -> list[dict]:
    """Per scene: text for TTS, words, estimated seconds, estimated start."""
    lead_in = pacing().get("lead_in", 0.0)
    rows, t = [], lead_in
    for s in data["scenes"]:
        text, trailing = split_trailing(flat(s["narration"]))
        n = len(words(text))
        after = float(s.get("pause_after_s", 0.0)) + trailing
        est = n / wpm * 60.0 + inline_pauses(text) + after
        rows.append({"scene": s, "text": text, "words": n, "after": after, "est": est, "start": t,
                     "chars": len(spoken(text))})
        t += est
    return rows


def pacing() -> dict:
    vt = VIDEO / "voice.toml"
    return tomllib.loads(vt.read_text()).get("pacing", {}) if vt.exists() else {}


def chapters_of(data: dict) -> list[dict]:
    return list(data["chapters"])


def by_chapter(data: dict, rows: list[dict]) -> list[tuple[dict, list[dict]]]:
    out = []
    for ch in chapters_of(data):
        out.append((ch, [r for r in rows if r["scene"]["chapter"] == ch["id"]]))
    return out


# ------------------------------------------------------------------ writers

def write_voiceover(data: dict, rows: list[dict]) -> str:
    lines = [f"<!-- {GENERATED} -->",
             "<!-- Inline [pause N] = extra silence inserted after the audio is generated (free).",
             "     A '> [pause N]' note = the silent beat before the next paragraph. *word* = emphasis (not spoken). -->",
             ""]
    last = None
    for i, r in enumerate(rows):
        s = r["scene"]
        if s["chapter"] != last:
            ch = next(c for c in data["chapters"] if c["id"] == s["chapter"])
            lines += [f"# {ch['title']}", ""]
            last = s["chapter"]
        lines += [f"<!-- scene: {s['id']} -->", r["text"], ""]
        if i < len(rows) - 1 and r["after"] > 0:
            lines += [f"> [pause {r['after']:g}]", ""]
    return "\n".join(lines).rstrip() + "\n"


def write_narration(data: dict, rows: list[dict], wpm: float) -> str:
    total = rows[-1]["start"] + rows[-1]["est"]
    nwords = sum(r["words"] for r in rows)
    v = data["video"]
    out = [f"# {v['title']}: narration", "",
           f"_{GENERATED}_", "",
           f"**{nwords} words · estimated {mmss(total)} at {wpm:g} wpm of speech plus planned silences "
           f"({nwords / (total / 60):.0f} wpm overall)**. "
           "A clean read-through: the pause marks live in `voiceover.md` and `plan/scenes.yaml`; *italics* mark "
           "emphasis; _silent beat_ is the pause after a scene.", ""]
    for ch, rs in by_chapter(data, rows):
        if not rs:
            continue
        dur = sum(r["est"] for r in rs)
        out += [f"## {ch['title']} · est. {mmss(dur)} (target {mmss(ch['target_s'])}) · {sum(r['words'] for r in rs)} words", ""]
        for r in rs:
            s = r["scene"]
            out += [f"### {s['id']} · {s['title']}",
                    f"_est. {mmss(r['start'])} to {mmss(r['start'] + r['est'])} · {r['words']} words_", "",
                    " ".join(PAUSE.sub(" ", r["text"]).split()), "",
                    f"_silent beat {r['after']:g} s_", ""]
    return "\n".join(out).rstrip() + "\n"


def tex(e: str) -> str:
    return f"`{e}`"


def write_scene_plan(data: dict, rows: list[dict], wpm: float) -> str:
    v = data["video"]
    total = rows[-1]["start"] + rows[-1]["est"]
    out = [f"# {v['title']}: scene plan", "", f"_{GENERATED}_", "",
           f"**Spine.** {flat(v['spine'])}", "",
           f"Estimated runtime **{mmss(total)}** ({sum(r['words'] for r in rows)} words at {wpm:g} wpm plus "
           f"planned silences). Target {mmss(v['target_runtime_s']['goal'])}, range "
           f"{mmss(v['target_runtime_s']['min'])} to {mmss(v['target_runtime_s']['max'])}.", "",
           "| Chapter | Scenes | Words | Est. | Target |", "|---|---|---|---|---|"]
    for ch, rs in by_chapter(data, rows):
        dur = sum(r["est"] for r in rs)
        out.append(f"| {ch['title']} | {len(rs)} | {sum(r['words'] for r in rs)} | {mmss(dur)} | {mmss(ch['target_s'])} |")
    out += ["", "## Open loops", "", "| Loop | Promise | Planted | Paid |", "|---|---|---|---|"]
    for lp in data["loops"]:
        out.append(f"| {lp['id']} | {lp['promise']} | {', '.join(lp['planted_in'])} | {', '.join(lp['paid_in'])} |")
    out += ["", "## Running datasets", "", "| Dataset | What it is | Used in |", "|---|---|---|"]
    for d in data["datasets"]:
        out.append(f"| {d['name']} | {flat(d['what'])} | {', '.join(d['used_in'])} |")
    out += ["", "## Layouts and the rail (the whiteboard rule)", "", "| Layout | Use |", "|---|---|"]
    for l in data["layouts"]:
        out.append(f"| {l['id']} · {l['name']} | {flat(l['use'])} |")
    out += ["", "| Rail board | Pinned in | Recalled in | Wiped at |", "|---|---|---|---|"]
    for bd in data["boards"]:
        out.append(f"| {bd['name']} | {bd['pinned_in']} | {', '.join(bd.get('recalled_in') or []) or '—'} | {bd['wiped_at']} |")
    for ch, rs in by_chapter(data, rows):
        dur = sum(r["est"] for r in rs)
        out += ["", f"## {ch['title']} · est. {mmss(dur)} (target {mmss(ch['target_s'])})", ""]
        if ch.get("lens"):
            out += [f"**Lens.** {ch['lens']}", ""]
        if ch.get("takeaway"):
            out += [f"**Takeaway.** {ch['takeaway']}", ""]
        if ch.get("concepts"):
            out += ["| Concept | Graphic | Equation | Animation |", "|---|---|---|---|"]
            for c in ch["concepts"]:
                eq = tex(c["equation"]) if c.get("equation") else "(picture only)"
                out.append(f"| {c['concept']} | {c['graphic']} | {eq} | {c['animation']} |")
            out.append("")
        for r in rs:
            s, vis = r["scene"], r["scene"]["visual"]
            out += [f"### {s['id']} · {s['title']}",
                    f"_{' + '.join(s['arc_step']) if isinstance(s['arc_step'], list) else s['arc_step']} · est. {mmss(r['start'])} to {mmss(r['start'] + r['est'])} "
                    f"({r['est']:.0f} s) · {r['words']} words · silent beat {r['after']:g} s_", "",
                    f"**Goal.** {s['goal']}", "",
                    f"> {r['text']}", "",
                    f"**Visual.** {flat(vis['description'])}", "",
                    "| Cue (at word) | Action |", "|---|---|"]
            for st in vis.get("reveal_sequence") or []:
                out.append(f"| {st['at_word']} | {st['action']} |")
            eqs = ", ".join(tex(e) for e in vis.get("equations") or []) or "none (the picture carries it)"
            eng = s["engines"]
            sec = f" + {', '.join(eng['secondary'])}" if eng.get("secondary") else ""
            out += ["", f"- **Equations:** {eqs}",
                    f"- **Camera:** {vis.get('camera', '')} · **Layers:** {', '.join(vis.get('layers') or [])}",
                    f"- **Engines:** {eng['primary']}{sec}. {s['engine_reason']}",
                    f"- **Retention:** {s['retention_device']} · **Interrupt:** {s.get('interrupt') or 'none'}",
                    f"- **Transition out:** {s['transition_out']}",
                    f"- **Sound:** {s['sfx_music']}"]
            if vis.get("layout"):
                out.append(f"- **Layout:** {vis['layout']}" + (f" · **Rail:** {', '.join(vis['rail'])}" if vis.get("rail") else ""))
            n_eq = len(vis.get("equations") or [])
            out += [f"- **∑** graphic ✓ · equation {'✓ ' + str(n_eq) if n_eq else '— (picture only)'} · "
                    f"animation ✓ {len(vis.get('reveal_sequence') or [])} cues", ""]
    return "\n".join(out).rstrip() + "\n"


def update_durations(rows: list[dict]) -> int:
    """Fill duration_s for estimate-sourced scenes, editing only those lines (comments and layout untouched)."""
    text, changed = SCENES.read_text(), 0
    for r in rows:
        s = r["scene"]
        if s.get("duration_source", "estimate") != "estimate":
            continue
        new = round(r["est"])
        block = re.compile(rf"(\n  - id: {re.escape(s['id'])}\n(?:(?!\n  - id: ).)*?\n    duration_s: )([0-9.]+)", re.S)
        m = block.search(text)
        if not m:
            sys.exit(f"duration_s line not found for {s['id']}")
        if float(m.group(2)) != new:
            text = text[: m.start(2)] + str(new) + text[m.end(2):]
            changed += 1
    SCENES.write_text(text)
    return changed


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--wpm", type=float, default=166.0, help="natural speech rate of the voice (words per minute)")
    ap.add_argument("--check", action="store_true", help="validate and summarise only; write nothing")
    a = ap.parse_args()

    data = load()
    errors = [e for s in data["scenes"] for e in check_cues(s)]
    rows = plan(data, a.wpm)
    total = rows[-1]["start"] + rows[-1]["est"]
    nwords = sum(r["words"] for r in rows)

    print(f"{len(rows)} scenes · {nwords} words · {sum(r['chars'] for r in rows)} characters of speech")
    for ch, rs in by_chapter(data, rows):
        dur = sum(r["est"] for r in rs)
        print(f"  {ch['title']:<18} {len(rs):>2} scenes {sum(r['words'] for r in rs):>4} words  "
              f"est {mmss(dur):>5}  target {mmss(ch['target_s']):>5}")
    print(f"estimated runtime {mmss(total)} at {a.wpm:g} wpm ({nwords / (total / 60):.0f} wpm overall)")
    for e in errors:
        print("✘", e)

    if not a.check:
        (VIDEO / "voiceover.md").write_text(write_voiceover(data, rows))
        (VIDEO / "script" / "narration_full.md").write_text(write_narration(data, rows, a.wpm))
        (VIDEO / "plan" / "scene_plan.md").write_text(write_scene_plan(data, rows, a.wpm))
        (VIDEO / "storyboard.md").write_text(
            "# Storyboard: video 016\n\nThis video's storyboard is generated from `plan/scenes.yaml`: read "
            "[plan/scene_plan.md](plan/scene_plan.md).\n")
        print(f"wrote voiceover.md, script/narration_full.md, plan/scene_plan.md, storyboard.md; "
              f"{update_durations(rows)} duration_s updated")
        tail = pacing().get("tail")
        if tail is not None and abs(float(tail) - rows[-1]["after"]) > 1e-6:
            print(f"note: voice.toml [pacing] tail = {tail}, last scene's silent beat = {rows[-1]['after']:g}")
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
