"""aion docs: print a topic doc, or rebuild llms.txt / llms-full.txt from the code."""

from __future__ import annotations

import click

BEGIN, END = "<!-- API:BEGIN (generated by `aion docs --build`) -->", "<!-- API:END -->"


def build(root) -> list[str]:
    from aion import catalog

    api, full = catalog.build_llms(root)
    llms = root / "llms.txt"
    text = llms.read_text()
    a, b = text.index(BEGIN) + len(BEGIN), text.index(END)
    llms.write_text(text[:a] + "\n" + api + text[b:])
    (root / "llms-full.txt").write_text(full)
    return [str(llms), str(root / "llms-full.txt")]


@click.command()
@click.argument("topic", required=False)
@click.option("--build", "do_build", is_flag=True, help="Regenerate llms.txt API section and llms-full.txt.")
def cli(topic, do_build):
    """List topics, print docs/<topic>.md, or --build the generated agent docs."""
    from aion._env import ROOT

    if do_build:
        for p in build(ROOT):
            click.echo(f"✔ {p}")
        return
    docs = ROOT / "docs"
    if not topic:
        for p in sorted(docs.glob("*.md")):
            first = next((l for l in p.read_text().splitlines() if l.strip()), "")
            click.echo(f"{p.stem:<14} {first.lstrip('# ')}")
        return
    p = docs / f"{topic}.md"
    if not p.exists():
        raise click.ClickException(f"no docs/{topic}.md (try `aion docs`)")
    click.echo(p.read_text())
