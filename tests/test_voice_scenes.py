def test_scene_markers_group_paragraphs(tmp_path):
    p = tmp_path / "v.md"
    p.write_text(SCRIPT)
    paras = read_paras(p)
    assert [q.scene for q in paras] == ["s01_open", "s02_buffon", "s02_buffon", "s03_close"]
    assert paras[0].text == "Sticks rain onto a floor of boards. Where is the circle hiding?"
    assert [q.section for q in paras] == [True, False, False, True]       # headings before s01 and in s03
    assert [q.pause for q in paras] == [0.0, 0.0, 1.5, 0.0]
    assert [(sid, len(ps)) for sid, ps in read_scenes(p)] == [("s01_open", 1), ("s02_buffon", 2), ("s03_close", 1)]

    p.write_text("<!-- scene: a -->\nHello there.\n<!-- scene: b -->\nSecond one.\n<!-- a note -->\n")
    assert [(sid, [q.text for q in ps]) for sid, ps in read_scenes(p)] == [("a", ["Hello there."]),
                                                                            ("b", ["Second one."])]
    for bad, msg in [("Before any marker.\n\n<!-- scene: a -->\nText.\n", "before the first"),
                     ("<!-- scene: a -->\nOne.\n\n<!-- scene: b -->\nTwo.\n\n<!-- scene: a -->\nThree.\n", "two"),
                     ("<!-- scene: two words -->\nText.\n", "bad scene marker")]:
        p.write_text(bad)
        with pytest.raises(ValueError, match=msg):
            read_scenes(p)


def test_inline_pauses_leave_the_text_and_become_breaks(tmp_path):
    p = tmp_path / "v.md"
    p.write_text("One two three. [pause 2] Four five.\n\nSix, [Pause .5 s] seven.[pause 1s]Eight\n\n"
                 "[pause 3]\n\nNine ten [pause 0.8s] eleven.\n")
    paras = read_paras(p)
    assert read_script(p) == ["One two three. Four five.", "Six, seven. Eight", "Nine ten eleven."]
    assert [q.breaks for q in paras] == [((3, 2.0),), ((1, 0.5), (2, 1.0)), ((2, 0.8),)]
    assert [q.pause for q in paras] == [0.0, 0.0, 3.0]                   # a pause-only paragraph moves on
    assert read_breaks(p) == [(3, 2.0), (6, 0.5), (7, 1.0), (10, 0.8)]   # global word indices
    warn = lint([q.text for q in paras], breaks=[q.breaks for q in paras])
    assert len([w for w in warn if "doesn't follow punctuation" in w]) == 1 and "'ten'" in warn[-1]
    assert lint(["Then [pause] wait."])[0].startswith("¶1: [pause] goes to the TTS as an audio tag")


def test_aliases_options_and_banned_words(tmp_path):
    toml = tmp_path / "voice.toml"
    toml.write_text(TOML)
    opts = ScriptOptions.load(toml)
    assert opts.chunking == "scene" and opts.aliases == {"Buffon": "Boo-fon"} and opts.banned == ("in fact", "crucial")
    assert ScriptOptions.load(tmp_path / "missing.toml") == ScriptOptions()
    said = apply_aliases('Buffon\'s needles, "Buffon." Buffonish', opts.aliases)
    assert said == 'Boo-fon\'s needles, "Boo-fon." Buffonish'
    assert [unalias(w, opts.aliases) for w in said.split()] == ["Buffon's", "needles,", '"Buffon."', "Buffonish"]
    for bad in ('chunking = "chapters"\n', '[aliases]\nZu = "Dzoo jir"\n'):
        toml.write_text(bad)
        with pytest.raises(ValueError):
            ScriptOptions.load(toml)
    warn = lint(["In fact, this is crucial. Infact, crucially, IN FACT.", "A pause—then more."],
                banned=["in fact", "crucial", "—"])
    hits = [w for w in warn if "banned" in w]
    assert len(hits) == 4 and sum("'in fact'" in w for w in hits) == 2 and sum("'—'" in w for w in hits) == 1


