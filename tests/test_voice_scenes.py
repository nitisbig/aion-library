def _cues(path):
    return [lines for _, _, lines in read_captions(path)]


def test_long_cue_splits_at_its_best_phrase_break(tmp_path):
    text = "Spin the wheel slowly, and watch the rim trace out its path."
    words = [Word(t, 0.52 * i, 0.52 * i + 0.5) for i, t in enumerate(text.split())]   # 6.22 s of speech
    out = tmp_path / "s.srt"
    write_subtitles(words, out, limits=None)
    assert len(_cues(out)) == 1                                           # the search alone keeps one cue
    write_subtitles(words, out)
    assert _cues(out) == [["Spin the wheel slowly,"], ["and watch the rim trace out its path."]]
    assert check_subtitles(out) == []


def test_short_cue_grows_into_free_time(tmp_path):
    seq = [("That", 0.0), ("is", 0.3), ("the", 0.6), ("idea.", 0.9), ("Yes.", 2.4), ("Then", 3.35), ("more.", 3.65)]
    words = [Word(t, s, s + 0.3) for t, s in seq]
    out = tmp_path / "s.srt"
    write_subtitles(words, out)
    caps = read_captions(out)
    yes = next(c for c in caps if c[2] == ["Yes."])
    assert yes[1] - yes[0] >= 1.0 and yes[1] <= next(c for c in caps if c[2][0].startswith("Then"))[0]
    assert check_subtitles(out) == []


def test_boxed_in_cue_merges_or_borrows_time():
    w = lambda t, s, e: Word(t, s, e)  # noqa: E731
    a = Caption([[w("It", 0.0, 0.5), w("is", 0.5, 1.0), w("round.", 1.0, 1.9)]], 0.0, 2.0)
    b = Caption([[w("Yes.", 2.0, 2.3)]], 2.0, 2.4)
    c = Caption([[w("Then", 2.4, 3.0), w("it", 3.0, 3.4), w("rolls.", 3.4, 4.2)]], 2.4, 4.4)
    out = _enforce([a, b, c], 42, 2, 1.0, 6.0)
    assert len(out) == 2 and all(1.0 <= x.end - x.start <= 6.0 for x in out)
    assert any(len(x.lines) == 2 and x.lines[1][0].text in ("Yes.", "Then") for x in out)

    long1 = [w(t, 0.1 * i, 0.1 * i + 0.1) for i, t in enumerate(("abcdefghi " * 8).split())]  # 2 full lines
    long2 = [w(t, 3.4 + 0.1 * i, 3.5 + 0.1 * i) for i, t in enumerate(("jklmnopqr " * 8).split())]
    p = Caption([long1[:4], long1[4:]], 0.0, 3.0)
    q = Caption([[w("Yes.", 3.0, 3.3)]], 3.0, 3.4)
    n = Caption([long2[:4], long2[4:]], 3.4, 6.0)
    out = _enforce([p, q, n], 42, 2, 1.0, 6.0)
    assert len(out) == 3 and out[1].end - out[1].start >= 1.0                     # no merge fits: borrowed
    assert out[0].end >= long1[-1].end and out[2].start <= long2[0].start + 0.5 and out[0].end <= out[1].start


def test_vtt_matches_srt_and_check_reports_violations(tmp_path):
    text = "Salt & pepper. Then a long line that keeps going for quite some time, and more."
    words = [Word(t, 0.4 * i, 0.4 * i + 0.35) for i, t in enumerate(text.split())]
    srt, vtt = tmp_path / "s.srt", tmp_path / "s.vtt"
    write_subtitles(words, srt)
    write_vtt(words, vtt)
    body = vtt.read_text()
    assert body.startswith("WEBVTT\n\n") and "Salt &amp; pepper." in body and " --> " in body
    assert re.search(r"\d\d:\d\d:\d\d\.\d{3} --> ", body) and not re.search(r"\d,\d{3} -->", body)
    assert read_captions(vtt) == read_captions(srt) and check_subtitles(vtt) == []

    bad = tmp_path / "bad.srt"
    bad.write_text("1\n00:00:00,000 --> 00:00:00,500\nfine\n\n"
                   "2\n00:00:00,400 --> 00:00:07,500\n" + "x" * 43 + "\ntwo\nthree\n")
    issues = check_subtitles(bad)
    for needle in ("under 1 s", "over 6 s", "3 lines", "43 characters", "starts before the previous cue ends"):
        assert any(needle in i for i in issues), needle
