def test_scene_requests_exports_and_timeline(tmp_path, tts):
    v = make_video(tmp_path)
    r = run(v)
    assert len(tts) == 3 and r["scenes"] == 3 and r["subtitle_violations"] == []
    s1, s2, s3 = tts
    assert "previous_text" not in s1 and s1["next_text"] == s2["text"]
    assert s2["previous_text"] == s1["text"] and s2["next_text"] == s3["text"] and "next_text" not in s3
    assert s2["text"] == "Boo-fon asked this, in seventeen seventy seven.\n\nBoo-fon's needles land at random."
    assert all("[pause" not in c["text"] and c["seed"] == 7 and c["model_id"] == "eleven_v4" for c in tts)
    assert s1["voice_settings"] == {"stability": 0.55}

    al = load(v.dir / "audio" / "alignment" / "s02_buffon.json")
    assert al["request"]["seed"] == 7 and al["request"]["take"] == 0 and al["request"]["model_id"] == "eleven_v4"
    assert al["request"]["text_sha"] == master._sha(s2["text"]) and al["request"]["prev_sha"] == master._sha(s1["text"])
    assert "".join(al["characters"]) == s2["text"] and len(al["character_end_times_seconds"]) == len(s2["text"])
    assert al["words"][0] == {**al["words"][0], "text": "Buffon", "said": "Boo-fon"}
    mp3 = (v.dir / "audio" / "scenes" / "s02_buffon.mp3").read_bytes()
    assert abs(al["duration"] - len(master.decode_pcm(mp3)) / RATE) < 1e-6

    words = load(v.assets / "words.json")
    texts = [w["text"] for w in words]
    assert "Buffon" in texts and "Buffon's" in texts and not any("Boo-fon" in t for t in texts)
    for name in ("subtitles.srt", "subtitles.vtt", "cue-per-word.srt"):
        body = (v.assets / name).read_text()
        assert "Buffon" in body and "Boo-fon" not in body
    assert check_subtitles(v.assets / "subtitles.vtt") == []

    rows = load(v.assets / "scenes.json")
    assert [x["id"] for x in rows] == ["s01_open", "s02_buffon", "s03_close"]
    assert set(rows[0]) == {"id", "start", "end", "speech_start", "speech_end", "first_word", "last_word",
                            "first_index", "last_index"}
    assert [(x["first_word"], x["last_word"]) for x in rows] == [("Sticks", "hiding?"), ("Buffon", "random."),
                                                                 ("So", "along.")]
    assert rows[0]["start"] == 0.0 and abs(rows[-1]["end"] - r["duration"]) < 1e-3
    for a, b in zip(rows, rows[1:]):
        assert a["end"] == b["start"] and a["speech_end"] < a["end"] < b["speech_start"]
    assert all(x["start"] <= x["speech_start"] < x["speech_end"] <= x["end"] for x in rows)
    assert [words[x["first_index"]]["text"] for x in rows] == ["Sticks", "Buffon", "So"]

    # pauses landed on the final timeline: inline 0.8 s, `> [pause 1.5]` + paragraph gap, section gap
    at = {w["text"]: w for w in words}
    assert at["Where"]["start"] - at["boards."]["end"] > 0.45 + 0.8 - 0.1
    assert at["Buffon's"]["start"] - at["seven."]["end"] > 0.45 + 1.5 + 0.5 - 0.1
    assert at["So"]["start"] - at["random."]["end"] > 1.0 + 0.2          # section gap + the clips' own edges

    man = load(v.dir / "audio" / "manifest.json")
    assert man["config"]["model_id"] == "eleven_v4" and [s["take"] for s in man["scenes"]] == [0, 0, 0]
    assert man["scenes"][1]["prev_text"] == s1["text"] and man["scenes"][1]["start"] == rows[1]["start"]


def test_scene_offsets_are_decoded_sample_counts(tmp_path, tts):
    """Without pacing, each scene's words start at the summed decoded length of the scenes before it."""
    script = "<!-- scene: a -->\nFirst scene here.\n\n<!-- scene: b -->\nSecond one.\n\n<!-- scene: c -->\nThird.\n"
    v = make_video(tmp_path, script, 'voice_id = "voice-x"\nchunking = "scene"\n')
    run(v)
    words, man = load(v.assets / "words.json"), load(v.dir / "audio" / "manifest.json")
    t0 = 0.0
    for s in man["scenes"]:
        local = load(v.dir / s["alignment"])["words"]
        assert abs(words[s["first_index"]]["start"] - (t0 + local[0]["start"])) < 2e-3
        t0 += s["clip_duration"]
    assert abs(t0 - man["duration"]) < 1e-3


def test_pinning_bills_only_the_edited_scene(tmp_path, tts):
    v = make_video(tmp_path)
    run(v)
    old = [c["text"] for c in tts]
    assert len(tts) == 3
    run(v)
    assert len(tts) == 3                                                  # nothing changed: all cached

    (v.dir / "voiceover.md").write_text(SCRIPT.replace("land at random", "fall at random"))
    jobs = master.plan(v).scenes
    assert [(j.status, j.why, j.stale_context) for j in jobs] == [
        ("cached", "pinned", True), ("bill", "text changed", False), ("cached", "pinned", True)]
    run(v)
    assert len(tts) == 4                                                  # only the edited scene was requested
    new2 = tts[-1]
    assert "fall at random" in new2["text"] and new2["previous_text"] == old[0] and new2["next_text"] == old[2]
    man = load(v.dir / "audio" / "manifest.json")
    assert man["scenes"][0]["next_text"] == old[1]                        # s01 keeps its recorded request

    run(v, scenes=["s01_open"])                                           # refresh s01's context on purpose
    assert len(tts) == 5 and tts[-1]["next_text"] == new2["text"] and "previous_text" not in tts[-1]
    assert load(v.dir / "audio" / "manifest.json")["scenes"][0]["next_text"] == new2["text"]
    run(v)
    assert len(tts) == 5


def test_retakes_use_new_seeds_and_keep_old_takes(tmp_path, tts):
    v = make_video(tmp_path)
    run(v)
    first = dict(tts[1])
    run(v, retake=["s02_buffon"])
    assert len(tts) == 4 and tts[-1]["seed"] == 8 and tts[-1]["text"] == first["text"]
    run(v, retake=["s02_buffon"])
    assert len(tts) == 5 and tts[-1]["seed"] == 9
    man = load(v.dir / "audio" / "manifest.json")
    assert [(s["take"], s["seed"]) for s in man["scenes"]] == [(0, 7), (2, 9), (0, 7)]
    assert load(v.dir / "audio" / "alignment" / "s02_buffon.json")["request"]["take"] == 2
    vs = VoiceSettings.load(v.dir / "voice.toml")
    assert is_cached(first["text"], first["previous_text"], first["next_text"], replace(vs, seed=7))  # take 0 kept
    run(v)
    assert len(tts) == 5                                                  # stays on take 2, free


def test_exported_takes_restore_after_a_cache_prune(tmp_path, tts):
    v = make_video(tmp_path)
    run(v)
    before = (v.assets / "words.json").read_text()
    shutil.rmtree(tmp_path / "cache")
    vp = master.plan(v)
