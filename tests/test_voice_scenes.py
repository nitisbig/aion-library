def fake_take(text: str) -> tuple[bytes, dict]:
    """(wav bytes, character alignment): a tone per word, tiny gaps inside phrases, real pauses at punctuation."""
    chars, starts, ends, spans = [], [], [], []
    t = 0.12
    for tok in re.split(r"(\s+)", text):
        if not tok:
            continue
        if tok.isspace():
            last = chars[-1] if chars else ""
            gap = 0.45 if last in ".?!" else 0.3 if last in ",;:" else 0.04
            for k, ch in enumerate(tok):
                chars.append(ch)
                starts.append(t + gap * k / len(tok))
                ends.append(t + gap * (k + 1) / len(tok))
            t += gap
            continue
        dur = 0.06 * len(tok) + 0.08
        for k, ch in enumerate(tok):
            chars.append(ch)
            starts.append(t + dur * k / len(tok))
            ends.append(t + dur * (k + 1) / len(tok))
        spans.append((t, t + dur))
        t += dur
    x = np.zeros(int((t + 0.15) * RATE), np.float32)
    for a, b in spans:
        i, j = int(a * RATE), int(b * RATE)
        x[i:j] = 0.4 * np.sin(2 * np.pi * 220 * np.arange(j - i) / RATE)
    buf = io.BytesIO()
    with wave.open(buf, "wb") as f:
        f.setnchannels(1)
        f.setsampwidth(2)
        f.setframerate(RATE)
        f.writeframes((x * 32767).astype("<i2").tobytes())
    return buf.getvalue(), {"characters": chars, "character_start_times_seconds": starts,
                            "character_end_times_seconds": ends}


class FakeResp:
    status_code = 200

    def __init__(self, body):
        self._body = body

    def json(self):
        return self._body


@pytest.fixture
def tts(tmp_path, monkeypatch):
    """Fake ElevenLabs: records every request body; nothing leaves the machine."""
    import requests

    from aion import _env, cache

    monkeypatch.setattr(cache, "CACHE", tmp_path / "cache")
    monkeypatch.setattr(_env, "MEDIA", tmp_path / "media")
    monkeypatch.setenv("ELEVENLABS_API_KEY", "test-key")
    calls = []

    def post(url, params, headers, json, timeout):
        assert headers["xi-api-key"] == "test-key" and url.endswith("/text-to-speech/voice-x/with-timestamps")
        calls.append(json)
        audio, align = fake_take(json["text"])
        return FakeResp({"audio_base64": base64.b64encode(audio).decode(), "alignment": align})

    monkeypatch.setattr(requests, "post", post)
    return calls


def make_video(tmp_path, script: str = SCRIPT, toml: str = TOML) -> VideoPaths:
    vdir = tmp_path / "015-test"
    (vdir / "assets").mkdir(parents=True)
    (vdir / "voiceover.md").write_text(script)
    (vdir / "voice.toml").write_text(toml)
    return VideoPaths(vdir)


def run(video, **kw):
    return master.generate(video, loudness=None, progress=False, **kw)


def load(path):
    return json.loads(path.read_text())


